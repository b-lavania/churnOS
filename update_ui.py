def get_help_text(label):
    desc = "Adjust this parameter to see its impact on the model."
    for key, val in tooltip_dict.items():
        if key.lower() in label.lower():
            desc = val
            break
    return f'help="{desc}"'

def process_file(filepath):
    with open(filepath, 'r') as f:
        content = f.read()

    # Clean emojis and em-dashes
    content = remove_emojis(content)
    content = remove_em_dashes(content)

    # Regex to find st.slider, st.number_input, st.selectbox, st.metric
    # We want to add `help="..."` to them if it doesn't exist.
    # Note: Regex parsing python code is fragile, but we'll do a simple string replacement for known patterns.
    # We'll match: st.slider("LABEL", ..., help="Adjust this parameter to see its impact on the model.") -> st.slider("LABEL", ..., help="...")
    
    # Let's use re.sub with a function
    def replacer(match):
        func = match.group(1)
        label_quote = match.group(2)
        label_text = match.group(3)
        rest = match.group(4)
        
        # If it already has help=, skip
        if "help=" in rest:
            return match.group(0)
            
        help_str = get_help_text(label_text)
        
        # We need to insert help_str at the end of the arguments, before the closing paren.
        # This is tricky because the closing paren might be on another line or part of a nested call.
        # But for simple calls on one line:
        if ")" in rest:
            # find the last parenthesis and insert before it
            last_paren_idx = rest.rfind(")")
            new_rest = rest[:last_paren_idx] + f", {help_str}" + rest[last_paren_idx:]
            return f'st.{func}({label_quote}{label_text}{label_quote}{new_rest}'
        
        return match.group(0)

    # Pattern: st.(slider|number_input|selectbox|metric)( ["']([^"']+)["'] (.*?) )
    # This is a very simplified pattern and assumes the label is the first argument and a simple string literal.
    pattern = r'st\.(slider|number_input|selectbox|metric)\(\s*(["\'])(.*?)\2(.*?\))'
    content = re.sub(pattern, replacer, content, flags=re.DOTALL)
    
    # Add expander to pages/*.py if not already there
    if "pages/" in filepath and "Concept Playbook" not in content and "def " not in content[:50]:
        # find the first st.markdown or title and insert after it
        lines = content.split('\n')
        insert_idx = -1
        for i, line in enumerate(lines):
            if "st.markdown" in line and "header" in line.lower():
                insert_idx = i + 2
                break
        
        if insert_idx != -1:
            expander_code = """
with st.expander("Concept Playbook: How to use this page"):
    st.markdown('''
    **Overview:** This page provides causal insights into your metrics.
    **How to use:** Adjust the inputs in the sidebar or main area to simulate different business scenarios. 
    Pay attention to the outputs with tooltips for detailed definitions. All metrics are connected to the central causal model.
    ''')
"""
            lines.insert(insert_idx, expander_code)
            content = '\n'.join(lines)

    with open(filepath, 'w') as f:
        f.write(content)

# Process all files
for root, dirs, files in os.walk('.'):
    if 'venv' in root or '.git' in root or '__pycache__' in root:
        continue
    for file in files:
        if file.endswith('.py'):
            filepath = os.path.join(root, file)
            try:
                process_file(filepath)
            except Exception as e:
                print(f"Error processing {filepath}: {e}")

print("Done processing files.")
