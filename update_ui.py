def remove_emojis(text):
    # Very basic emoji removal (removing non-ascii characters that are likely emojis)
    # We'll just strip out common emoji ranges or use a library if available.
    # Instead, let's just strip actual emoji characters using a regex pattern.
    emoji_pattern = re.compile(
        u"(\ud83d[\ude00-\ude4f])|"  # emoticons
        u"(\ud83c[\udf00-\uffff])|"  # symbols & pictographs (1 of 2)
        u"(\ud83d[\u0000-\uddff])|"  # symbols & pictographs (2 of 2)
        u"(\ud83d[\ude80-\udeff])|"  # transport & map symbols
        u"(\ud83c[\udde0-\uddff])"  # flags (iOS)
        "+", flags=re.UNICODE)
    # Actually, a simpler way in python 3 is to encode to ascii and ignore, but that strips all unicode.
    # Let's just remove the ones we know are there: , , , , , , , , , , , , , , , , , , 
    known_emojis = ["", "", "", "", "", "", "", "", "", "", "", "", "", "", ""]
    for e in known_emojis:
        text = text.replace(e, "")
    return text

def remove_em_dashes(text):
    return text.replace(":", ":").replace(":", ":")

